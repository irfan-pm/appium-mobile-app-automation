// ---------- Core navigation helpers ----------

async function ensureLoggedOut() {
  await driver.terminateApp(APP_PACKAGE);
  await driver.activateApp(APP_PACKAGE);
  const onWelcome = await welcomeLoginButton().waitForDisplayed({ timeout: 8000 }).catch(() => false);
  if (onWelcome) return;

  // Something is logged in from a previous test - wipe app data for a clean, deterministic start.
  await driver.execute('mobile: clearApp', { appId: APP_PACKAGE });
  // clearApp revokes runtime permissions; the camera prompt would otherwise pop up over the
  // barcode-enabled Select Product screen and swallow taps.
  await driver
    .execute('mobile: changePermissions', {
      action: 'grant',
      appPackage: APP_PACKAGE,
      permissions: ['android.permission.CAMERA'],
    })
    .catch(() => {});
  await driver.activateApp(APP_PACKAGE);
  await welcomeLoginButton().waitForDisplayed({ timeout: 15000 });
}

async function dismissCameraPrompt() {
  const allowCamera = el('While using the app');
  if (await allowCamera.isDisplayed().catch(() => false)) await allowCamera.click();
}

