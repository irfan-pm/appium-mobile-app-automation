// Uses UiAutomator's native scrollIntoView against the drawer's scrollable container -
// far more reliable than manual swipe-and-check loops for a long, deeply nested menu.
async function drawerTap(text) {
  const locator = driver.$(
    `android=new UiScrollable(new UiSelector().scrollable(true).instance(0)).scrollIntoView(new UiSelector().textContains("${text}").instance(0))`
  );
  await locator.waitForDisplayed({ timeout: 10000 });
  await locator.click();
}

