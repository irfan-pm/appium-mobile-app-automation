// Finds a list row by its visible text, taps the 3-dot menu to its right, then taps
// the named menu option. Mirrors the row-icon pattern used in brand.test.js / product.test.js.
async function openRowContextMenu(rowText, menuOptionText) {
  await driver.execute('mobile: hideKeyboard').catch(() => {});
  const row = rowEl(rowText);
  await row.waitForDisplayed({ timeout: 10000 });
  const loc = await row.getLocation();
  const option = el(menuOptionText);
  let menuOpen = false;
  for (let attempt = 0; attempt < 3 && !menuOpen; attempt++) {
    await driver.execute('mobile: clickGesture', { x: 999, y: Math.round(loc.y) + 26 });
    menuOpen = await option.waitForDisplayed({ timeout: 4000 }).catch(() => false);
  }
  if (!menuOpen) {
    throw new Error(`Could not open the row context menu for "${rowText}" (looking for "${menuOptionText}")`);
  }
  await option.click();
}

