// The Companies list grows with every test run - search to isolate a specific
// row before interacting with it, rather than assuming it is on-screen unfiltered.
async function searchOnCompaniesScreen(term) {
  const field = selectCompanySearchField(); // shares the same hint as the Select Company screen
  const alreadyThere = await field.waitForDisplayed({ timeout: 8000 }).catch(() => false);
  if (!alreadyThere) {
    // Saving sometimes lands somewhere other than the list - re-navigate to it fresh.
    await openDrawer();
    await drawerTap('Companies');
    await field.waitForDisplayed({ timeout: 15000 });
  }
  await field.clearValue().catch(() => {});
  await field.setValue(term);
  await driver.pause(1200);
  // The keyboard stays open after typing - the first tap on a row's 3-dot menu
  // just dismisses it instead of opening the menu, so close it explicitly here.
  await driver.execute('mobile: hideKeyboard').catch(() => {});
}

// The plan allows only a handful of extra companies, so every test that creates one
// must remove it again or later tests hit "Plan Limit Exceeded".
async function deleteCompanyByName(name) {
  try {
    await searchOnCompaniesScreen(name);
  } catch (e) {
    // Some forms (e.g. Change Password) land somewhere other than the list - start fresh.
    await goToCompaniesScreen();
    await searchOnCompaniesScreen(name);
  }
  await openRowContextMenu(name, 'Delete');
  const confirmYes = driver.$('~Yes');
  const hasConfirm = await confirmYes.waitForDisplayed({ timeout: 4000 }).then(() => true).catch(() => false);
  if (hasConfirm) await confirmYes.click();
  await driver.pause(2000);
}

