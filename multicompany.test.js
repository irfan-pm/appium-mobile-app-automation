// Taps "Add Product" on an open Add Invoice / Add Shipment form, picks a product from the
// search results, and confirms the line item via "Add Item". Leaves the caller back on the
// parent form with the product line added.
async function addProductLineToForm(productName) {
  const addProductBtn = driver.$('~Add Product');
  await addProductBtn.waitForDisplayed({ timeout: 15000 });

  // Tapping this has proven flaky (native .click() and coordinate taps both
  // occasionally no-op) - retry a few times rather than trusting a single attempt.
  let onSelectProduct = false;
  for (let attempt = 0; attempt < 3 && !onSelectProduct; attempt++) {
    const loc = await addProductBtn.getLocation();
    const size = await addProductBtn.getSize();
    await driver.execute('mobile: clickGesture', {
      x: Math.round(loc.x + size.width / 2),
      y: Math.round(loc.y + size.height / 2),
    });
    await dismissCameraPrompt();
    onSelectProduct = await selectProductSearchField().waitForDisplayed({ timeout: 7000 }).catch(() => false);
  }
  if (!onSelectProduct) {
    throw new Error('Could not reach the Select Product screen after retrying "Add Product"');
  }

  await selectProductSearchField().setValue(productName);
  await driver.pause(1500);
  await el(productName).waitForDisplayed({ timeout: 10000 });
  await driver.execute('mobile: hideKeyboard').catch(() => {});

  // The Select Product screen has its own always-visible "Add Item" footer (it creates a
  // brand-new product), so success here means we LEFT that screen, not that "Add Item" exists.
  const productRow = driver.$(`android=new UiSelector().descriptionContains("${productName}")`);
  let onProductDetail = false;
  for (let attempt = 0; attempt < 4 && !onProductDetail; attempt++) {
    await dismissCameraPrompt();
    await productRow.click().catch(() => {});
    await driver.pause(1500);
    await dismissCameraPrompt();
    const stillOnList = await selectProductSearchField().isDisplayed().catch(() => false);
    onProductDetail = !stillOnList;
  }
  if (!onProductDetail) {
    throw new Error('Could not open the product detail after retrying product selection');
  }

  await driver.$('~Add Item').waitForDisplayed({ timeout: 10000 });
  await driver.$('~Add Item').click();
  await driver.pause(1000);
}

